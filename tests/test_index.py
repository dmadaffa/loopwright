def test_typo_in_one_file_does_not_hide_its_id_from_references(tmp_path):
    make_task(tmp_path, "features", 1, type="epic")  # invalid, but id 1 exists
    make_task(tmp_path, "features", 2, depends="[1]")

    result = run_index(tmp_path)

    assert result.returncode == 1
    assert "no task with id" not in result.stderr


